-- Per-level placement history for SNAGD.
create table if not exists public.snagd_placement_history (
    id bigint generated by default as identity primary key,
    level_key text not null,
    level_name text not null,
    event_type text not null check (event_type in ('added', 'repositioned', 'removed')),
    previous_rank integer,
    new_rank integer,
    reason text not null default '',
    changed_by uuid references auth.users(id) on delete set null,
    changed_at timestamptz not null default now(),
    constraint snagd_placement_history_rank_check
        check ((previous_rank is null or previous_rank > 0) and (new_rank is null or new_rank > 0))
);

create index if not exists snagd_placement_history_level_changed_idx
    on public.snagd_placement_history (level_key, changed_at desc);

alter table public.snagd_placement_history enable row level security;

grant select on public.snagd_placement_history to anon, authenticated;
grant insert on public.snagd_placement_history to authenticated;
grant usage, select on sequence public.snagd_placement_history_id_seq to authenticated;

drop policy if exists "Public can read placement history" on public.snagd_placement_history;
create policy "Public can read placement history"
    on public.snagd_placement_history for select
    to anon, authenticated
    using (true);

drop policy if exists "Staff can insert placement history" on public.snagd_placement_history;
create policy "Staff can insert placement history"
    on public.snagd_placement_history for insert
    to authenticated
    with check (
        changed_by = auth.uid()
        and exists (
            select 1 from public.snagd_staff
            where user_id = auth.uid()
        )
    );
