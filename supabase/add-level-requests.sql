-- Run once in the Supabase SQL Editor to enable requests for unlisted levels.
create table if not exists public.snagd_level_requests (
    id bigint generated by default as identity primary key,
    level_name text not null,
    level_id bigint not null,
    verifier text not null,
    verification_url text not null,
    aredl_rank integer,
    status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
    created_at timestamptz not null default now(),
    reviewed_at timestamptz
);

alter table public.snagd_level_requests enable row level security;

drop policy if exists "Anyone can request an unlisted level" on public.snagd_level_requests;
create policy "Anyone can request an unlisted level"
on public.snagd_level_requests for insert
to anon, authenticated
with check (
    status = 'pending'
    and reviewed_at is null
    and length(trim(level_name)) between 1 and 100
    and level_id > 0
    and length(trim(verifier)) between 1 and 50
    and verification_url like 'https://%'
    and (aredl_rank is null or aredl_rank > 0)
);

drop policy if exists "SNAGD staff can read level requests" on public.snagd_level_requests;
create policy "SNAGD staff can read level requests"
on public.snagd_level_requests for select
to authenticated
using (
    exists (select 1 from public.snagd_staff where user_id = auth.uid())
);

drop policy if exists "SNAGD staff can review level requests" on public.snagd_level_requests;
create policy "SNAGD staff can review level requests"
on public.snagd_level_requests for update
to authenticated
using (
    exists (select 1 from public.snagd_staff where user_id = auth.uid())
)
with check (
    exists (select 1 from public.snagd_staff where user_id = auth.uid())
);
